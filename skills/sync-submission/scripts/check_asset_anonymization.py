# Generic institution / ethics-board tokens (English + Korean). No proper names.
INSTITUTION_RE = re.compile(
    r"\b(?:Hospital|Hospitals|University|Universit[äe]t|College of Medicine|"
    r"School of Medicine|Faculty of Medicine|Medical Cent(?:er|re)|Health System|"
    r"Cancer Cent(?:er|re)|Infirmary|Institutional Review Board|"
    r"IRB(?:[\s.:#-]*(?:No|Number|#)|\s*approval)?)\b"
    r"|병원|의료원|의과대학|대학교|연구윤리",
    re.IGNORECASE,
)

# docx/pdf metadata authorship values that are NOT a real person (tools/blanks).
TOOL_AUTHORS = (
    "unknown", "microsoft office user", "pandoc", "libreoffice", "writer",
    "openoffice", "word", "microsoft word", "google", "overleaf", "latex",
    "pdftex", "pdflatex", "xelatex", "lualatex", "quarto", "rmarkdown",
    "knitr", "wps", "author",
)

# .docx-only additions: python-docx writes "python-docx" as dc:creator, this
# repository's templates write "medsci-skills", and "Anonymous" is a neutral placeholder.
DOCX_TOOL_VALUES = frozenset(("python-docx", "python-pptx", "medsci-skills", "anonymous"))
# In a .docx every tool/placeholder value is matched EXACTLY on the normalised whole
# value — never by prefix, which would pass "author.smith@example.org" or
# "Author (Jane Doe)" as the placeholder "Author". TOOL_AUTHORS keeps its prefix
# matching for the PDF path only.
DOCX_TOOL_EXACT = frozenset(TOOL_AUTHORS) | DOCX_TOOL_VALUES
# Tools that may carry a version: the tool name followed only by a version number.
DOCX_TOOL_VERSIONED_RE = re.compile(
    r"^(?:microsoft office word|microsoft word|word|libreoffice|openoffice|pandoc|wps"
    r"|python-docx|quarto)[ /]v?\d+(?:\.\d+)*$")

# docProps/app.xml Company values that are an install default or a neutral/tool
# value, not an organisation. Its own list, matched exactly; the person-tool list
# does not apply to Company ("Google" is an organisation).
TOOL_COMPANIES = frozenset(("microsoft", "home", "personal")) | DOCX_TOOL_VALUES


def _is_tool_author(value: str) -> bool:
    """True if a metadata author value is blank or a known tool (not a person)."""
    v = value.strip().lower()
    if not v:
        return True
    return any(v == t or v.startswith(t) for t in TOOL_AUTHORS)


def _norm(value: str) -> str:
    return " ".join(value.split()).lower()


def _is_docx_tool_value(value: str) -> bool:
    v = _norm(value)
    return not v or v in DOCX_TOOL_EXACT or DOCX_TOOL_VERSIONED_RE.match(v) is not None

FIG_SCRIPT_GLOBS = ("*.R", "*.r", "*.py")

# OOXML namespaces, transitional and strict. Values are read by namespace URI + local
# name from parsed XML, never by regex over text: a regex misses single-quoted or
# re-prefixed attributes, CDATA, entities and UTF-16 parts, and matches text in a
# paragraph that merely looks like an attribute.
NS_DC = "http://purl.org/dc/elements/1.1/"
NS_CP = "http://schemas.openxmlformats.org/package/2006/metadata/core-properties"
NS_EP = ("http://schemas.openxmlformats.org/officeDocument/2006/extended-properties",
         "http://purl.oclc.org/ooxml/officeDocument/extendedProperties")
NS_W = ("http://schemas.openxmlformats.org/wordprocessingml/2006/main",
        "http://purl.oclc.org/ooxml/wordprocessingml/main")
NS_W15 = "http://schemas.microsoft.com/office/word/2012/wordml"
CORE_PERSON_TAGS = {f"{{{NS_DC}}}creator": "dc:creator",
                    f"{{{NS_CP}}}lastModifiedBy": "cp:lastModifiedBy"}
NS_CT = "http://schemas.openxmlformats.org/package/2006/content-types"
# docProps/app.xml: Manager is a person (the document's supervisor); Company is an
# organisation. Word fills Company from the installation, so it is often the employer.
APP_MANAGER_TAGS = {f"{{{ns}}}Manager" for ns in NS_EP}
APP_COMPANY_TAGS = {f"{{{ns}}}Company" for ns in NS_EP}
# Revision / comment authors: w:author on w:ins, w:del, w:comment, w:rPrChange,
# w:pPrChange and friends, in every XML part under word/ — tracked formatting changes
# to styles and list levels live in styles.xml / numbering.xml, and building blocks in
# glossary/document.xml, outside the body parts an earlier allow-list named.
W_AUTHOR_ATTRS = {f"{{{ns}}}author" for ns in NS_W}
# word/people.xml only: <w15:person w15:author="…"><w15:presenceInfo w15:providerId="AD"
# w15:userId="S::name@org::guid"/>. The userId is the editor's account (a sign-in
# address, a Microsoft-account id, or the display name when providerId is "None") and
# survives renaming w15:author to a neutral value.
W15_PERSON = f"{{{NS_W15}}}person"
W15_PRESENCE = f"{{{NS_W15}}}presenceInfo"
W15_AUTHOR = f"{{{NS_W15}}}author"
W15_PROVIDER = f"{{{NS_W15}}}providerId"
W15_USERID = f"{{{NS_W15}}}userId"
# Field codes. A complex field runs from <w:fldChar w:fldCharType="begin"> to "end", its
# instruction split over <w:instrText> runs (<w:delInstrText> inside a tracked deletion);
# a simple field keeps the whole instruction in <w:fldSimple w:instr="…">. Pieces are
# joined per field, never across fields.
W_INSTR_TAGS = {f"{{{ns}}}{n}" for ns in NS_W for n in ("instrText", "delInstrText")}
W_FLDCHAR_TAGS = {f"{{{ns}}}fldChar" for ns in NS_W}
W_FLDCHAR_TYPE = {f"{{{ns}}}fldCharType" for ns in NS_W}
W_FLDSIMPLE_TAGS = {f"{{{ns}}}fldSimple" for ns in NS_W}
W_INSTR_ATTRS = {f"{{{ns}}}instr" for ns in NS_W}
# Zotero citation data, in a ZOTERO_ITEM field or (bookmark mode) a ZOTERO_BREF_* custom
# property: `[ADDIN ]ZOTERO_ITEM CSL_CITATION {json}`, where each entry of "citationItems"
# has "uris":["http://zotero.org/users/1234567/items/ABCD2345"] (a personal synced
# library) or .../groups/7654321/items/... (a group library); older documents write "uri".
# Only those keys of the citation items are read: a Zotero link elsewhere (an item's URL
# field, a hyperlink, another reference manager's field) is somebody's web address, not
# this document's library. "users/local/<key>" (never synced) has no account id.
ZOTERO_ITEM_CODE = re.compile(r"^\s*(?:ADDIN\s+)?ZOTERO_ITEM\b")
ZOTERO_ITEM_PATH = re.compile(r"^/(users|groups)/([0-9]+)/items/[A-Za-z0-9]+/?$", re.ASCII)
ZOTERO_URIS_TEXT = re.compile(r'"uris?"\s*:\s*(\[[^\]]*\]|"[^"]*")')
ZOTERO_URL_TEXT = re.compile(r'https?:[^"\s\]]+')
ZOTERO_BREF = re.compile(r"^(ZOTERO_BREF_.+)_([0-9]+)$", re.ASCII)
NS_CUSTOM_PROPS = ("http://schemas.openxmlformats.org/officeDocument/2006/custom-properties",
                   "http://purl.oclc.org/ooxml/officeDocument/customProperties")
CUSTOM_PROPERTY_TAGS = {f"{{{ns}}}property" for ns in NS_CUSTOM_PROPS}


def _zotero_library_ids(code: str) -> list[str]:
    """Library ids ("user 123", "group 456") in the citation items of one ZOTERO_ITEM code."""
    if not ZOTERO_ITEM_CODE.match(code):
        return []
    urls: list[str] = []
    start = code.find("{")
    try:
        data, _ = json.JSONDecoder().raw_decode(code[start:]) if start >= 0 else ({}, 0)
        items = data.get("citationItems") if isinstance(data, dict) else None
        for item in items if isinstance(items, list) else []:
            for key in ("uris", "uri"):
                v = item.get(key) if isinstance(item, dict) else None
                urls += [u for u in (v if isinstance(v, list) else [v]) if isinstance(u, str)]
    except ValueError:
        # Not valid JSON (cut off, or hand-edited): read the uris keys from the text so
        # that a damaged field is not passed as clean.
        text = re.sub(r"\\u002f", "/", code, flags=re.IGNORECASE).replace("\\/", "/")
        for m in ZOTERO_URIS_TEXT.finditer(text):
            urls += ZOTERO_URL_TEXT.findall(m.group(1))
    out: list[str] = []
    for u in urls:
        try:
            parts = urlsplit(u.strip())
        except ValueError:
            continue
        m = ZOTERO_ITEM_PATH.match(parts.path)
        if m and (parts.hostname or "").lower() in ("zotero.org", "www.zotero.org"):
            v = f"{'user' if m.group(1) == 'users' else 'group'} {m.group(2)}"
            if v not in out:
                out.append(v)
    return out


class _FieldCodes:
    """Collects each field's instruction text from one part's start/end events.

    A nested field has its own buffer. Within one field, current text (`w:instrText`)
    and tracked-deleted text (`w:delInstrText`) are kept apart, so an edit inside a code
    is not read as one string that was never there.
    """

    def __init__(self) -> None:
        self.stack: list[tuple[list[str], list[str]]] = []
        self.fields: list[str] = []

    def on_start(self, el) -> None:
        if el.tag in W_FLDSIMPLE_TAGS:
            for key in W_INSTR_ATTRS:
                if el.get(key):
                    self.fields.append(el.get(key))
        elif el.tag in W_FLDCHAR_TAGS:
            kind = next((el.get(k) for k in W_FLDCHAR_TYPE if el.get(k)), "")
            if kind == "begin":
                self.stack.append(([], []))
            elif kind == "end" and self.stack:
                self._close()

    def on_end(self, el) -> None:
        if el.tag in W_INSTR_TAGS and el.text and self.stack:
            current, deleted = self.stack[-1]
            (deleted if el.tag.endswith("delInstrText") else current).append(el.text)

    def _close(self) -> None:
        for pieces in self.stack.pop():
            if pieces:
                self.fields.append("".join(pieces))

    def flush(self) -> None:
        """A part cut off inside a field still yields what the open fields held."""
        while self.stack:
            self._close()


# Absolute home-dir path leaked into an OOXML attribute (e.g. a drawing's
# <pic:cNvPr descr="/Users/<user>/.../fig.png">). pandoc embeds the source image
# path as the picture description when given an absolute path; it carries the
# username into the docx body XML, invisible to a rendered-text scan.
DOCX_ABS_PATH_RE = re.compile(
    r'(/(?:Users|home)/[^\s<>"\']+|[A-Za-z]:[\\/]+Users[\\/]+[^\s<>"\']+)'
)


@dataclass
class Finding:
    type: str
    severity: str  # "leak" | "review"
    path: str
    detail: str


@dataclass
class Report:
    findings: list[Finding] = field(default_factory=list)
    scanned: dict[str, int] = field(default_factory=dict)
    poppler_available: bool = False
    skipped: list[str] = field(default_factory=list)

    @property
    def has_leak(self) -> bool:
        return any(f.severity == "leak" for f in self.findings)

    def submission_safe(self, strict: bool) -> bool:
        if self.has_leak:
            return False
        if strict and any(f.severity == "review" for f in self.findings):
            return False
        return True

    def as_dict(self, strict: bool) -> dict:
        return {
            "submission_safe": self.submission_safe(strict),
            "strict": strict,
            "poppler_available": self.poppler_available,
            "scanned": self.scanned,
            "skipped": self.skipped,
            "summary": {
                "leak": sum(1 for f in self.findings if f.severity == "leak"),
                "review": sum(1 for f in self.findings if f.severity == "review"),
            },
            "findings": [asdict(f) for f in self.findings],
        }


def _is_under_figures(p: Path) -> bool:
    return any(part.lower().startswith(("figure", "fig", "graphic")) for part in p.parts)


def _load_names(names_file: Path | None) -> list[str]:
    if not names_file:
        return []
    out = []
    for line in names_file.read_text(encoding="utf-8", errors="replace").splitlines():
        s = line.strip()
        if s and not s.startswith("#"):
            out.append(s)
    return out


def _name_hits(text: str, names: list[str]) -> list[str]:
    low = text.lower()
    return [n for n in names if n.lower() in low]


def _pdftotext(pdf: Path) -> str | None:
    try:
        r = subprocess.run(["pdftotext", "-q", str(pdf), "-"],
                           capture_output=True, text=True, timeout=60)
        return r.stdout
    except Exception:
        return None


def _pdf_author(pdf: Path) -> str | None:
    try:
        r = subprocess.run(["pdfinfo", str(pdf)], capture_output=True, text=True, timeout=30)
    except Exception:
        return None
    author = creator = ""
    for line in r.stdout.splitlines():
        if line.startswith("Author:"):
            author = line.split(":", 1)[1].strip()
        elif line.startswith("Creator:"):
            creator = line.split(":", 1)[1].strip()
    for v in (author, creator):
        if v and not _is_tool_author(v):
            return v
    return None


@dataclass
class DocxPeople:
    """Person-bearing values found in one .docx, each with the 'part attribute' it came from."""
    metadata: list[tuple[str, str]] = field(default_factory=list)   # core/app person properties
    companies: list[tuple[str, str]] = field(default_factory=list)  # app.xml Company
    authors: list[tuple[str, str]] = field(default_factory=list)    # w:author / w15:author
    accounts: list[tuple[str, str]] = field(default_factory=list)   # people.xml presenceInfo userId
    ref_ids: list[tuple[str, str]] = field(default_factory=list)    # Zotero library ids ("user 123", places)
    unreadable: list[str] = field(default_factory=list)             # "part: reason"


def _add_place(found: dict[str, list[str]], value: str, place: str) -> None:
    places = found.setdefault(value, [])
    if place not in places:
        places.append(place)


def _scan_part(z: zipfile.ZipFile, info: zipfile.ZipInfo, on_start, on_end,
               unreadable: list[str], clear: bool = True) -> None:
    """Stream one XML part from bytes: on_start(el) sees attributes as soon as a start
    tag is complete (so a part truncated after it still yields it), on_end(el) sees the
    element's text.

    Values already collected are kept when the part fails part-way, and the failure is
    recorded as unreadable (reported as `review`, which fails under --strict).
    ElementTree does not fetch external entities or DTDs.
    """
    try:
        with z.open(info) as fh:
            for event, el in ET.iterparse(fh, events=("start", "end")):
                if event == "start":
                    if on_start:
                        on_start(el)
                    continue
                if on_end:
                    on_end(el)
                if clear:
                    el.clear()
    except Exception as exc:  # CRC error, malformed XML, unknown encoding, ...
        unreadable.append(f"{info.filename}: {type(exc).__name__}: {exc}")


def _xml_parts_by_content_type(z: zipfile.ZipFile, unreadable: list[str]) -> set[str]:
    """Lower-cased part names that [Content_Types].xml declares as XML, so a word/ part
    stored under another extension (e.g. comments.wml) is still read."""
    ct = next((i for i in z.infolist() if i.filename.lower() == "[content_types].xml"), None)
    if ct is None:
        return set()
    overrides: set[str] = set()
    defaults: set[str] = set()

    def is_xml(ctype: str) -> bool:
        c = ctype.strip().lower()
        return c.endswith("+xml") or c in ("application/xml", "text/xml")

    def on_end(el):
        if el.tag == f"{{{NS_CT}}}Override" and is_xml(el.get("ContentType", "")):
            overrides.add(el.get("PartName", "").lstrip("/").lower())
        elif el.tag == f"{{{NS_CT}}}Default" and is_xml(el.get("ContentType", "")):
            defaults.add(el.get("Extension", "").lower())

    _scan_part(z, ct, None, on_end, unreadable)
    found = set(overrides)
    for info in z.infolist():
        low = info.filename.lower()
        if "." in low and low.rsplit(".", 1)[1] in defaults:
            found.add(low)
    return found


def _docx_people(docx: Path) -> DocxPeople:
    out = DocxPeople()
    authors: dict[str, list[str]] = {}
    accounts: dict[str, list[str]] = {}
    ref_ids: dict[str, list[str]] = {}

    def note_library_ids(data: str, place: str) -> None:
        for v in _zotero_library_ids(data):
            _add_place(ref_ids, v, place)

    try:
        z = zipfile.ZipFile(docx)
    except Exception as exc:
        out.unreadable.append(f"(package): {type(exc).__name__}: {exc}")
        return out
    with z:
        infos = z.infolist()
        seen: dict[str, int] = {}
        for info in infos:
            seen[info.filename] = seen.get(info.filename, 0) + 1
        for name, n in seen.items():
            if n > 1:  # Word reads one copy; the other may still carry a name
                out.unreadable.append(f"{name}: duplicate ZIP entry name ({n} copies)")
        xml_by_type = _xml_parts_by_content_type(z, out.unreadable)

        def visit_core(name):
            def on_end(el):
                attr = CORE_PERSON_TAGS.get(el.tag)
                if attr:
                    v = "".join(el.itertext()).strip()
                    if v and not _is_docx_tool_value(v):
                        out.metadata.append((v, f"{name} {attr}"))
            return on_end

        def visit_app(name):
            def on_end(el):
                if el.tag in APP_MANAGER_TAGS:
                    v = "".join(el.itertext()).strip()
                    if v and not _is_docx_tool_value(v):
                        out.metadata.append((v, f"{name} Manager"))
                elif el.tag in APP_COMPANY_TAGS:
                    v = "".join(el.itertext()).strip()
                    if v and _norm(v) not in TOOL_COMPANIES:
                        out.companies.append((v, f"{name} Company"))
            return on_end

        def visit_word(name):
            people = name.lower() == "word/people.xml"

            def on_start(el):
                for key, raw in el.attrib.items():
                    if key in W_AUTHOR_ATTRS:
                        v = raw.strip()
                        if v and not _is_docx_tool_value(v):
                            _add_place(authors, v, f"{name} w:author")
                if not people:
                    return
                if el.tag == W15_PERSON:
                    v = el.get(W15_AUTHOR, "").strip()
                    if v and not _is_docx_tool_value(v):
                        _add_place(authors, v, f"{name} w15:author")
                elif el.tag == W15_PRESENCE:
                    v = el.get(W15_USERID, "").strip()
                    provider = el.get(W15_PROVIDER, "")
                    # Under providerId "None" (exactly, as Word writes it) the userId is
                    # only a display name, so a neutral one is fine; under any other
                    # provider (AD, Windows Live, "NONE", ...) it is treated as an account
                    # and any non-empty value is reported.
                    neutral = provider == "None" and _is_docx_tool_value(v)
                    if v and not neutral:
                        _add_place(accounts, v, f"{name} w15:userId (providerId={provider or '?'})")
            return on_start

        def visit_custom(chunks):
            # Bookmark-mode citations: ZOTERO_BREF_<id>_<n> properties hold one citation's
            # data in numbered chunks. Other properties are not citation data.
            def on_end(el):
                if el.tag not in CUSTOM_PROPERTY_TAGS:
                    return
                m = ZOTERO_BREF.match(el.get("name", ""))
                if m:
                    value = "".join("".join(child.itertext()) for child in el)
                    chunks.setdefault(m.group(1), []).append((int(m.group(2)), value))
            return on_end

        for info in infos:
            name = info.filename
            low = name.lower()
            if low == "docprops/core.xml":
                # Property parts are tiny: keep children so a value split across child
                # elements is still read whole.
                _scan_part(z, info, None, visit_core(name), out.unreadable, clear=False)
            elif low == "docprops/app.xml":
                _scan_part(z, info, None, visit_app(name), out.unreadable, clear=False)
            elif low == "docprops/custom.xml":
                chunks: dict[str, list[tuple[int, str]]] = {}
                _scan_part(z, info, None, visit_custom(chunks), out.unreadable, clear=False)
                for parts in chunks.values():
                    parts.sort()
                    # Chunks are numbered 1..n; with one missing or repeated the value
                    # cannot be rebuilt, and joining the rest could invent an id.
                    if [n for n, _ in parts] == list(range(1, len(parts) + 1)):
                        note_library_ids("".join(v for _, v in parts), f"{name} custom property")
            elif low.startswith("word/") and (low.endswith(".xml") or low in xml_by_type):
                fields = _FieldCodes()
                word_start = visit_word(name)

                def on_start(el, word_start=word_start, fields=fields):
                    word_start(el)
                    fields.on_start(el)

                _scan_part(z, info, on_start, fields.on_end, out.unreadable)
                fields.flush()
                for code in fields.fields:
                    note_library_ids(code, f"{name} field code")
    out.authors = [(v, "; ".join(p)) for v, p in authors.items()]
    out.accounts = [(v, "; ".join(p)) for v, p in accounts.items()]
    out.ref_ids = [(v, "; ".join(p)) for v, p in ref_ids.items()]
    return out


def _docx_embedded_abs_paths(docx: Path) -> list[str]:
    """Home paths in OOXML content, custom properties, or relationships.

    A rendered-text scan misses custom CSL/bibliography properties, and a
    word/*.xml-only scan misses both docProps/ and external .rels targets.
    """
    hits: list[str] = []
    try:
        with zipfile.ZipFile(docx) as z:
            parts = [n for n in z.namelist() if n.endswith((".xml", ".rels"))]
            for name in parts:
                xml = z.read(name).decode("utf-8", errors="replace")
                for m in DOCX_ABS_PATH_RE.finditer(xml):
                    hits.append(m.group(1))
    except Exception:
        return []
    # de-dup, preserve order
    seen: set[str] = set()
    out = []
    for h in hits:
        if h not in seen:
            seen.add(h)
            out.append(h)
    return out


def build_report(root: Path, names: list[str], poppler: bool) -> Report:
    rep = Report(poppler_available=poppler)
    scripts = docx_files = pdf_files = 0

    for p in sorted(root.rglob("*")):
        if not p.is_file() or "__pycache__" in p.parts:
            continue
        suffix = p.suffix.lower()
        rel = str(p.relative_to(root))

        # 1. figure-generating scripts AND the config files that drive them.
        #
        # A figure builder does not have to be a script. `/make-figures` documents its STROBE
        # builder as `build_strobe_template.py --config figures/figure1_strobe.yaml`, and the first
        # box of a STROBE flow diagram is exactly where "Patients screened at <Hospital>" lives.
        # Scanning only .r/.py meant the identical institution string blocked in one file and
        # passed in the other:
        #
        #   figures/figure1_strobe.py    -> FAIL: institution-like token in figure script
        #   figures/figure1_strobe.yaml  -> PASS: no anonymization leak  ({'figure_scripts': 0})
        #
        # For a double-blind submission that is an anonymity leak which the anonymisation gate
        # declared clean. The builders in this repo parse YAML and JSON alike, so both are now read
        # the way the scripts already were — as text, line by line, which is all this check needs.
        if suffix in (".r", ".py", ".yaml", ".yml", ".json") and _is_under_figures(p):
            scripts += 1
            text = p.read_text(encoding="utf-8", errors="replace")
            for i, line in enumerate(text.splitlines(), 1):
                if INSTITUTION_RE.search(line):
                    rep.findings.append(Finding(
                        "figure_script_institution", "review", f"{rel}:{i}",
                        f"institution-like token in figure script: {line.strip()[:120]}"))
                for n in _name_hits(line, names):
                    rep.findings.append(Finding(
                        "figure_script_name", "leak", f"{rel}:{i}",
                        f"name '{n}' hardcoded in figure script"))

        # 2 + 3. docx metadata
        elif suffix == ".docx":
            docx_files += 1
            people = _docx_people(p)
            for a, where in people.metadata:
                rep.findings.append(Finding(
                    "docx_metadata_author", "leak", rel,
                    f"docx author metadata: '{a}' ({where})"))
            for c, where in people.companies:
                rep.findings.append(Finding(
                    "docx_metadata_company", "review", rel,
                    f"docx Company property names an organisation: '{c}' ({where})"))
            for a, where in people.authors:
                rep.findings.append(Finding(
                    "docx_revision_author", "leak", rel,
                    f"tracked-change/comment author: '{a}' ({where}) — a blinded file needs a "
                    f"neutral author (e.g. 'Author') or none; set it when the changes are made"))
            for a, where in people.accounts:
                rep.findings.append(Finding(
                    "docx_revision_author", "leak", rel,
                    f"editor account id: '{a}' ({where}) — renaming the author does not remove "
                    f"it; remove that w15:presenceInfo element (or its whole w15:person) and re-check"))
            for a, where in people.ref_ids:
                rep.findings.append(Finding(
                    "docx_reference_manager_id", "review", rel,
                    f"Zotero library id in citation data: '{a}' ({where}) — an account or group "
                    f"number that links documents written from the same library; for a blinded copy, "
                    f"unlink the citations (Zotero: Unlink Citations) in that copy, keeping the "
                    f"linked original"))
            # A part that could not be read was not checked: never let it pass silently.
            for msg in people.unreadable:
                rep.skipped.append(f"docx part not readable: {rel} {msg}")
                rep.findings.append(Finding(
                    "docx_part_unreadable", "review", rel,
                    f"could not be read, so its authors were not checked: {msg}"))
            # 4. absolute home-dir path embedded in word/*.xml (e.g. pic descr)
            for ap_ in _docx_embedded_abs_paths(p):
                rep.findings.append(Finding(
                    "docx_embedded_abs_path", "leak", rel,
                    f"absolute path in docx XML (username leak; use a relative "
                    f"image path + pandoc --resource-path): {ap_}"))

        # PDFs: metadata + (figure) rendered-text
        elif suffix == ".pdf":
            pdf_files += 1
            if poppler:
                a = _pdf_author(p)
                if a:
                    rep.findings.append(Finding(
                        "pdf_metadata_author", "leak", rel, f"pdf author/creator: '{a}'"))
                if _is_under_figures(p):
                    txt = _pdftotext(p)
                    if txt is None:
                        rep.skipped.append(f"pdftotext failed: {rel}")
                    elif txt.strip():
                        rep.findings.append(Finding(
                            "figure_rendered_text", "review", rel,
                            "figure PDF carries rendered text — visual-check for "
                            "institution/IRB#/author labels a text scan cannot see"))
                        if INSTITUTION_RE.search(txt):
                            rep.findings.append(Finding(
                                "figure_text_institution", "review", rel,
                                "institution-like token in figure PDF text"))
                        for n in _name_hits(txt, names):
                            rep.findings.append(Finding(
                                "figure_text_name", "leak", rel,
                                f"name '{n}' in figure PDF text"))
            else:
                rep.skipped.append(f"poppler unavailable, PDF not scanned: {rel}")

    rep.scanned = {"figure_scripts": scripts, "docx": docx_files, "pdf": pdf_files}
    return rep


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Submission-stage asset/figure/metadata anonymization gate.")
    ap.add_argument("--dir", type=Path, default=Path.cwd(),
                    help="Root directory to scan (default: cwd).")
    ap.add_argument("--names-file", type=Path, default=None,
                    help="Newline-separated institution/author names to flag (local only).")
    ap.add_argument("--out", type=Path, default=None, help="Write JSON report here.")
    ap.add_argument("--strict", action="store_true",
                    help="Also fail on 'review' findings (institution tokens, rendered text).")
    ap.add_argument("--quiet", action="store_true", help="Suppress stdout summary.")
    args = ap.parse_args(argv)

    if not args.dir.is_dir():
        print(f"ERROR: --dir not a directory: {args.dir}", file=sys.stderr)
        return 2
    if args.names_file is not None and not args.names_file.is_file():
        print(f"ERROR: --names-file not a file: {args.names_file}", file=sys.stderr)
        return 2

    poppler = shutil.which("pdftotext") is not None and shutil.which("pdfinfo") is not None
    names = _load_names(args.names_file)
    rep = build_report(args.dir, names, poppler)
    safe = rep.submission_safe(args.strict)

    if args.out is not None:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps({"detector": "check_asset_anonymization", **rep.as_dict(args.strict)}, indent=2), encoding="utf-8")

    if not args.quiet:
        if not poppler:
            print("NOTE: poppler (pdftotext/pdfinfo) not found — PDF text/metadata "
                  "checks skipped; install poppler-utils for full coverage.")
        if safe:
            n = len(rep.findings)
            print(f"PASS: no anonymization leak ({rep.scanned}; {n} advisory finding(s)).")
        else:
            print(f"FAIL: anonymization findings — {rep.as_dict(args.strict)['summary']}")
            for f in rep.findings:
                print(f"  - [{f.severity}] {f.type} {f.path}: {f.detail}")

    return 0 if safe else 1


if __name__ == "__main__":
    sys.exit(main())
