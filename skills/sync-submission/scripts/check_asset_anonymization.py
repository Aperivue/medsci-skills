#!/usr/bin/env python3
"""
check_asset_anonymization.py — submission-stage asset/peripheral anonymization gate.

Body-text anonymization is mature; the blind spot is *peripheral artifacts*. A
double-anonymized submission was nearly broken because a flow-diagram figure,
generated by a script with a hardcoded institution label, carried the real
hospital name — invisible to any docx text scan. File metadata (docx
`dc:creator`, PDF `/Author`) is a second blind spot.

This detector scans a submission/project directory for four deterministic
classes of leak:

  1. **figure-script hardcoded institution** — a figure-generating script
     (`figures/**/*.R|*.py`, or any `*.R|*.py` under a `figures*` dir) contains
     an institution-like token (Hospital / University / Medical Center / IRB /
     병원 / 의료원 …) or a name supplied via --names-file.
  2. **figure/asset PDF rendered text** — a figure PDF's extracted text carries
     an institution token or a --names-file name (de-anonymization risk). When a
     figure carries *any* rendered text, a `visual_check` advisory is emitted
     (text scanning cannot see rasterized labels).
  3. **document metadata author** — a `.docx` `dc:creator`/`cp:lastModifiedBy`
     (`docProps/core.xml`) or `Manager` (`docProps/app.xml`), or a `.pdf`
     Author/Creator, is a real person/identifier (not empty / not a known tool).
     A non-empty `Company` (`docProps/app.xml`) names an organisation, not a
     person, and is reported as `review` (fails only under --strict), like an
     institution token.
     Tracked changes and comments carry their own author, which core.xml does not
     show: a marked-up file whose metadata is scrubbed can still name every
     editor on every change. `w:author` is read in every XML part under `word/`
     (a `.xml` name, or declared XML in `[Content_Types].xml`) —
     body, notes, headers, comments, and also `styles.xml`/`numbering.xml`
     (tracked formatting changes, `w:rPrChange`/`w:pPrChange`) and
     `glossary/document.xml` — and, in `word/people.xml` only, `w15:person/@w15:author`
     and `w15:presenceInfo/@w15:userId` (an account id or sign-in address; a
     neutral value is accepted only under providerId exactly "None").
     Tool/placeholder values are matched exactly on the whole value in a .docx
     ("Author" passes, "Author (Jane Doe)" does not); a few tools may carry a
     version number ("LibreOffice/7.6").
     Citations inserted with the Zotero word-processor plugin from a synced library
     store the library's numeric id in the citation data
     (`zotero.org/users/<id>/items/...`, or `groups/<id>`), in field codes
     (a `ZOTERO_ITEM` field, complex or simple) under `word/` and, in bookmark mode,
     in `ZOTERO_BREF_*` properties of `docProps/custom.xml`. Only the citation's own
     `uris` are read, not a Zotero link elsewhere in the file. The id is an account or group number, not a name, and
     documents written from the same library can be linked by it: it is
     reported as `review` (`docx_reference_manager_id`). A local, unsynced library
     (`users/local/...`) carries no account id and is not reported.
     Parts are parsed as XML from bytes and matched by namespace + local name, so
     quoting, prefixes, CDATA, entities and UTF-16 do not hide a value. A part that
     cannot be read, or a duplicated ZIP entry name, is reported
     (`docx_part_unreadable`, review — fails under --strict) and does not discard
     what other parts yielded. Each finding names the part and attribute.
  4. **docx embedded absolute path** — any XML part or relationship carries
     an absolute home-dir path (Unix or Windows), including drawing descriptions
     and custom properties. Pandoc can retain local CSL/bibliography source paths
     in `docProps/custom.xml` even when the rendered document contains no path.
     Use relative image paths and strip source metadata after citation processing.

Severity:
  - `leak`   — metadata author present, or a --names-file name found anywhere.
  - `review` — institution-token hit, a docx `Company` property, a Zotero library
    id in citation data, a docx part that could not be read, or a figure carries
    rendered text.

Not read: bookmark names (`w:bookmarkStart w:name`). Pandoc writes `ref-<citekey>`
and hashed `X<hex>` ids, Word `_GoBack`/`_Toc…`/`_Ref…`/`_Hlk…`; neither has a
documented form that carries a person or account, and a citekey is free text, so
a pattern would mostly flag citations. Comment `w:initials` are not read either.

Exit: 0 = clean, 1 = findings (any `leak`; also `review` under --strict),
2 = usage/error. Degrades gracefully when poppler (pdftotext/pdfinfo) is absent:
script-grep and docx-metadata checks still run; PDF text/metadata checks are
reported as skipped (poppler_available:false) rather than silently passing.

Patterns are generic — no real names are baked in. Supply institution/author
names locally with --names-file (one per line); that file is never committed.

Stdlib-only.

Usage:
    python3 check_asset_anonymization.py --dir submission/ [--names-file names.txt]
        [--out qc/asset_anon.json] [--strict] [--quiet]
"""

